create extension if not exists pgcrypto;

create table if not exists public.workout_templates (
  id bigint generated by default as identity primary key,
  goal text not null,
  title text not null,
  summary text not null,
  place text not null check (place in ('home','gym')),
  workout_type text not null check (workout_type in ('bodyweight','equipment','mixed')),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (goal,title,place,workout_type)
);

create table if not exists public.exercise_guides (
  exercise_name text primary key,
  media_type text not null check (media_type in ('image','video','pending')),
  media_url text,
  source_title text,
  source_url text,
  source_name text,
  author text,
  license_name text,
  license_url text,
  ai_generated boolean not null default false,
  format_note text,
  pending_reason text,
  updated_at timestamptz not null default now()
);

create table if not exists public.trainer_profiles (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  display_name text not null,
  avatar text not null default '🏋️',
  verified boolean not null default false,
  follower_label text,
  bio text,
  activity_score integer not null default 0,
  is_public boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.public_routines (
  id uuid primary key default gen_random_uuid(),
  trainer_id uuid not null references public.trainer_profiles(id) on delete cascade,
  slug text not null unique,
  title text not null,
  summary text not null,
  exercises jsonb not null default '[]'::jsonb check (jsonb_typeof(exercises)='array'),
  duration integer not null check (duration between 5 and 180),
  level text not null,
  place text not null check (place in ('home','gym')),
  workout_type text not null check (workout_type in ('bodyweight','equipment','mixed')),
  is_featured boolean not null default false,
  is_public boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists one_featured_public_routine on public.public_routines(is_featured) where is_featured=true;

create table if not exists public.user_plans (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  goal text not null,
  level text not null,
  frequency integer not null check (frequency between 1 and 7),
  duration integer not null check (duration between 5 and 180),
  place text not null check (place in ('home','gym')),
  workout_type text not null check (workout_type in ('bodyweight','equipment','mixed')),
  caution text not null default '',
  plan_items jsonb not null default '[]'::jsonb check (jsonb_typeof(plan_items)='array'),
  completed_item_ids jsonb not null default '[]'::jsonb check (jsonb_typeof(completed_item_ids)='array'),
  app_state jsonb not null default '{}'::jsonb check (jsonb_typeof(app_state)='object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workout_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  workout_item_id text not null,
  title text not null,
  duration integer not null check (duration between 1 and 300),
  completed_at timestamptz not null default now(),
  unique (user_id,workout_item_id)
);

alter table public.workout_templates enable row level security;
alter table public.exercise_guides enable row level security;
alter table public.trainer_profiles enable row level security;
alter table public.public_routines enable row level security;
alter table public.user_plans enable row level security;
alter table public.workout_logs enable row level security;

drop policy if exists "Public can read active workout templates" on public.workout_templates;
create policy "Public can read active workout templates" on public.workout_templates for select to anon,authenticated using (is_active=true);
drop policy if exists "Public can read exercise guides" on public.exercise_guides;
create policy "Public can read exercise guides" on public.exercise_guides for select to anon,authenticated using (true);
drop policy if exists "Public can read trainer profiles" on public.trainer_profiles;
create policy "Public can read trainer profiles" on public.trainer_profiles for select to anon,authenticated using (is_public=true);
drop policy if exists "Public can read public routines" on public.public_routines;
create policy "Public can read public routines" on public.public_routines for select to anon,authenticated using (is_public=true);

drop policy if exists "Users can read their own plans" on public.user_plans;
create policy "Users can read their own plans" on public.user_plans for select to authenticated using (auth.uid()=user_id);
drop policy if exists "Users can insert their own plans" on public.user_plans;
create policy "Users can insert their own plans" on public.user_plans for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users can update their own plans" on public.user_plans;
create policy "Users can update their own plans" on public.user_plans for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "Users can delete their own plans" on public.user_plans;
create policy "Users can delete their own plans" on public.user_plans for delete to authenticated using (auth.uid()=user_id);

drop policy if exists "Users can read their own logs" on public.workout_logs;
create policy "Users can read their own logs" on public.workout_logs for select to authenticated using (auth.uid()=user_id);
drop policy if exists "Users can insert their own logs" on public.workout_logs;
create policy "Users can insert their own logs" on public.workout_logs for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users can update their own logs" on public.workout_logs;
create policy "Users can update their own logs" on public.workout_logs for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "Users can delete their own logs" on public.workout_logs;
create policy "Users can delete their own logs" on public.workout_logs for delete to authenticated using (auth.uid()=user_id);

grant select on public.workout_templates,public.exercise_guides,public.trainer_profiles,public.public_routines to anon,authenticated;
grant select,insert,update,delete on public.user_plans,public.workout_logs to authenticated;
grant usage,select on sequence public.workout_templates_id_seq to authenticated;
